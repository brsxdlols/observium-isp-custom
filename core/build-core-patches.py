#!/usr/bin/env python3
"""Build *private, review-only* unified patches for an exact Observium CE baseline.

No network, writes to Observium, credentials, or auto-apply. Uses two tar files:
 - official unmodified Observium CE .tar.gz
 - private evidence tar.gz exported from customized installation

Outputs individual .patch files, a JSON manifest of before/after SHA256, and
an informative report. Never publishes patches or vendor source.
"""
import argparse
import difflib
import hashlib
import json
import os
import re
import sys
import tarfile
from datetime import datetime, timezone
from pathlib import Path, PurePosixPath

FILES = (
    'html/includes/navbar.inc.php',
    'html/ajax/widget.php',
    'html/includes/dashboard-generate.inc.php',
    'html/pages/dashboard.inc.php',
    'html/js/dashboard.js',
)
MAX_SIZE = 2_000_000


def sha(data):
    return hashlib.sha256(data).hexdigest()


def members(tar):
    # Only regular entries; reject duplicated paths to avoid ambiguity.
    out = {}
    for entry in tar:
        name = PurePosixPath(entry.name)
        if entry.name.startswith('/') or '..' in name.parts or entry.issym() or entry.islnk():
            raise ValueError('Archive contains unsafe path/link: ' + entry.name)
        if entry.isfile():
            if entry.name in out:
                raise ValueError('Duplicate archive path: ' + entry.name)
            out[entry.name] = entry
    return out


def read_required(tar, index, path):
    m = index.get(path)
    if not m:
        raise ValueError('Missing required file: ' + path)
    if m.size > MAX_SIZE:
        raise ValueError('Source too large: ' + path)
    f = tar.extractfile(m)
    if f is None:
        raise ValueError('Unreadable: ' + path)
    content = f.read(MAX_SIZE + 1)
    if len(content) > MAX_SIZE or b'\0' in content:
        raise ValueError('Not a valid text source: ' + path)
    return content


def expected_hashes(content):
    result = {}
    for line in content.splitlines():
        line = line.strip()
        m = re.fullmatch(rb'([0-9a-f]{64})\s+(html/[^\s]+)', line)
        if m:
            result[m.group(2).decode()] = m.group(1).decode()
    return result


def source_version(index):
    # Presence of release metadata is only a hint, never proof of identical revisions.
    matched = [n for n in index if n.startswith('observium/') and
               (n.endswith('/version.php') or n.endswith('/version.inc.php'))]
    return matched[:5]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--baseline', required=True, help='Original official, unmodified Observium tar.gz')
    parser.add_argument('--evidence', required=True, help='Private tar.gz generated by --core-export')
    parser.add_argument('--out', required=True, help='New output directory (must not exist)')
    args = parser.parse_args()
    baseline = Path(args.baseline).resolve()
    evidence = Path(args.evidence).resolve()
    target = Path(args.out).resolve()
    if not baseline.is_file() or not evidence.is_file():
        parser.error('Both archive files must exist')
    if target.exists():
        parser.error('Output directory already exists; refusing to overwrite')
    # Read and verify ALL inputs BEFORE creating any output.
    all_diffs = []
    report = []
    with tarfile.open(baseline, 'r:gz') as src, tarfile.open(evidence, 'r:gz') as customized:
        bidx, eidx = members(src), members(customized)
        manifest = read_required(customized, eidx, 'manifest.txt')
        expected = expected_hashes(manifest)
        for rel in FILES:
            a = read_required(src, bidx, 'observium/' + rel)
            b = read_required(customized, eidx, 'files/' + rel)
            if rel not in expected or sha(b) != expected[rel]:
                raise ValueError('Private evidence SHA mismatch: ' + rel)
            try:
                left = a.decode('utf-8')
                right = b.decode('utf-8')
            except UnicodeDecodeError:
                raise ValueError('Source is not UTF-8: ' + rel)
            diff = ''.join(difflib.unified_diff(left.splitlines(True), right.splitlines(True),
                        fromfile='a/' + rel, tofile='b/' + rel, n=3))
            all_diffs.append((rel, diff))
            report.append({'path':rel, 'baseline_sha256':sha(a),
                           'customized_sha256':sha(b), 'changed':a != b,
                           'diff_lines':len(diff.splitlines())})
    # Output is deliberately PRIVATE because diffs can contain identifiers or secrets.
    target.mkdir(mode=0o700, parents=True)
    os.chmod(target, 0o700)
    for rel, diff in all_diffs:
        path = target / (rel.replace('/', '__') + '.patch')
        path.write_text(diff, encoding='utf-8')
        path.chmod(0o600)
    metadata = {
        'format':'observium-isp-core-review-v1',
        'generated_utc': datetime.now(timezone.utc).isoformat(),
        'baseline_archive_sha256': sha(baseline.read_bytes()),
        'evidence_archive_sha256': sha(evidence.read_bytes()),
        'warning':'NOT VALIDATED FOR AUTOMATIC APPLICATION. Verify same Observium release/revision and sanitize diffs before publication.',
        'files':report,
    }
    manifest = target / 'manifest.json'
    manifest.write_text(json.dumps(metadata, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    manifest.chmod(0o600)
    print('PRIVATE PATCH REVIEW DIRECTORY:', target)
    for r in report:
        print(('DIFF' if r['changed'] else 'SAME') + ': ' + r['path'] + ' (%s lines)' % r['diff_lines'])
    print('IMPORTANT: Patches are NOT approved for install or public upload.')
    print('Next: compare the Observium release/revision and inspect each patch for private values.')


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError, tarfile.TarError) as exc:
        print('ERROR:', exc, file=sys.stderr)
        sys.exit(1)